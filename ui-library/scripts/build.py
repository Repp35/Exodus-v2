#!/usr/bin/env python3
"""Bundle standard Roblox ModuleScripts without runtime HTTP or loadstring dependencies."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT.parent / 'exodus hub/modules/front/library.luau'
REQUIRE = re.compile(r'require\(script((?:\.[A-Za-z_][A-Za-z_0-9]*)+)\)')

def bundle(entry='init'):
    modules = {p.relative_to(ROOT / 'src').with_suffix('').as_posix(): p.read_text() for p in (ROOT / 'src').rglob('*.luau')}
    def rewrite(name, source):
        def resolve(match):
            # init.luau is the root ModuleScript; all other files are leaf ModuleScripts.
            parts = [] if name == 'init' else name.split('/')
            for part in match[1].split('.')[1:]:
                if part == 'Parent':
                    if not parts: raise ValueError(f'{name}: require escapes package')
                    parts.pop()
                else: parts.append(part)
            target = '/'.join(parts)
            if target not in modules: raise ValueError(f'{name}: unknown module {target}')
            return f'__require("{target}")'
        return REQUIRE.sub(resolve, source)
    output = ['-- GENERATED by ui-library/scripts/build.py. Edit ui-library/src instead.', 'local __factories, __cache, __loading = {}, {}, {}', 'local function __require(name)', '  if __cache[name] ~= nil then return __cache[name] end', '  assert(not __loading[name], "Circular module: " .. name)', '  __loading[name] = true', '  local value = __factories[name]()', '  __loading[name] = nil; __cache[name] = value', '  return value', 'end']
    for name, source in sorted(modules.items()):
        output += [f'__factories["{name}"] = function()', rewrite(name, source), 'end']
    output.append(f'return __require("{entry}")')
    return '\n'.join(output) + '\n'

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path, default=TARGET)
    args = parser.parse_args()
    result = bundle()
    if args.check:
        if not args.output.exists() or args.output.read_text() != result: raise SystemExit('Bundle is stale; run python3 ui-library/scripts/build.py')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(result)
    print(f'{args.output.relative_to(ROOT.parent) if args.output.is_relative_to(ROOT.parent) else args.output}: {len(result.encode())} bytes')
if __name__ == '__main__': main()
